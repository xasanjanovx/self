import re as _re

_ID_BY_EMOJI: dict[str, str] = {}
for _k, _v in PLAIN_TO_ID.items():
    _ID_BY_EMOJI[_k] = _v
for _k, _v in _ALIASES.items():
    if _v in PLAIN_TO_ID:
        _ID_BY_EMOJI[_k] = PLAIN_TO_ID[_v]

_EMOJI_RE = _re.compile("(" + "|".join(_re.escape(k) for k in sorted(_ID_BY_EMOJI, key=len, reverse=True)) + r")️?")
_SKIP_RE = _re.compile(r"(<tg-emoji[^>]*>.*?</tg-emoji>|<code>.*?</code>|<pre>.*?</pre>|<[^>]+>)", _re.S)


def id_for(emoji_char: str) -> str | None:
    return _ID_BY_EMOJI.get(str(emoji_char or "").replace("️", ""))


def premiumize(text: str | None) -> str | None:
    """Заменить обычные эмодзи на <tg-emoji> там, где есть премиум-аналог."""
    if not text or "<tg-emoji" in text and text.count("<tg-emoji") > 40:
        return text

    def _swap(m: "_re.Match[str]") -> str:
        char = m.group(1)
        return f'<tg-emoji emoji-id="{_ID_BY_EMOJI[char]}">{m.group(0)}</tg-emoji>'

    parts = _SKIP_RE.split(text)
    out = []
    for i, part in enumerate(parts):
        if i % 2 == 1:  # разделитель — тег/уже премиум/код
            out.append(part)
        else:
            out.append(_EMOJI_RE.sub(_swap, part))
    return "".join(out)
