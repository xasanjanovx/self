_BY_ID = {q.id: q for q in BANK}


def _file(uid: int):
    from .tg_user import data_dir

    return data_dir() / f"wake_quiz_{uid}.json"


def _load(uid: int) -> dict[str, Any]:
    try:
        return json.loads(_file(uid).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {"asked": []}


def _save(uid: int, state: dict[str, Any]) -> None:
    try:
        _file(uid).write_text(json.dumps(state, ensure_ascii=False), encoding="utf-8")
    except OSError:
        logger.warning("quiz state not saved", exc_info=True)


def for_day(uid: int, day: date) -> Q:
    """Вопрос на этот день: весь день один и тот же (повторные звонки), завтра — следующий по сложности."""
    state = _load(uid)
    if state.get("day") == day.isoformat() and state.get("today") in _BY_ID:
        return _BY_ID[state["today"]]
    asked = [x for x in state.get("asked") or [] if x in _BY_ID]
    fresh = [q for q in BANK if q.id not in asked]
    if not fresh:
        # всё спросили — второй круг с середины банка (лёгкие не повторяем)
        asked = []
        fresh = list(BANK[len(BANK) // 2:])
    pick = fresh[0]
    _save(uid, {"asked": asked + [pick.id], "day": day.isoformat(), "today": pick.id})
    return pick


def prompt_block(q: Q) -> str:
    """Кусок системного промпта звонка: вопрос, ответ и точный арабский."""
    lines = [f"ВОПРОС ДНЯ (задай ровно его, своими словами на языке разговора): {q.q}", f"Правильный ответ: {q.a}"]
    if q.ar:
        lines.append(f"Точный арабский текст (если нужно произнести — читай СЛОВО В СЛОВО, ничего не меняя и не дописывая): {q.ar}")
    if q.ref:
        lines.append(f"Источник: {q.ref}")
    return "\n".join(lines)


def card(q: Q, lang: str = "ru") -> str:
    """Сообщение в чат после подъёма — с точным арабским."""
    from html import escape

    uz = lang == "uz"
    out = ["📿 <b>" + ("Kun savoli" if uz else "Вопрос дня") + "</b>", escape(q.q), "", "✅ " + escape(q.a)]
    if q.ar:
        out += ["", f"<b>{escape(q.ar)}</b>"]
    if q.ref:
        out.append(f"<i>{escape(q.ref)}</i>")
    return "\n".join(out)


